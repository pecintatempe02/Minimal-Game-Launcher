#!/bin/sh
# Install or remove Minimal Game Launcher for the current user only.
#
# Usage:
#   scripts/install.sh              install under $PREFIX (default: ~/.local)
#   scripts/install.sh --uninstall  remove the installed files
#
# Installed files:
#   $PREFIX/lib/minimal-game-launcher/minimal_game_launcher/   Python package
#   $PREFIX/bin/minimal-game-launcher                          entry point
#   $PREFIX/share/applications/<app-id>.desktop                desktop entry
#   $PREFIX/share/icons/hicolor/scalable/apps/<app-id>.svg     icon
#
# User data (library, prefixes, covers, settings, logs) is never touched.
# Nothing here requires root.

set -eu

APP_ID=io.github.minimal_game_launcher.MinimalGameLauncher
COMMAND_NAME=minimal-game-launcher
PREFIX=${PREFIX:-$HOME/.local}
: "${PREFIX:?PREFIX must not be empty}"

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
LIB_DIR=$PREFIX/lib/minimal-game-launcher
BIN_PATH=$PREFIX/bin/$COMMAND_NAME
DESKTOP_PATH=$PREFIX/share/applications/$APP_ID.desktop
ICON_PATH=$PREFIX/share/icons/hicolor/scalable/apps/$APP_ID.svg

die() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

# Quote a value for a POSIX shell single-quoted string.
sh_quote() {
    printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
}

# Quote a value for the Exec= key of a desktop entry (spec section 6.5).
desktop_exec_quote() {
    escaped=$(printf '%s' "$1" | sed 's/[\\"`$]/\\&/g; s/%/%%/g')
    printf '"%s"' "$escaped"
}

refresh_caches() {
    if command -v update-desktop-database >/dev/null 2>&1; then
        update-desktop-database -q "$PREFIX/share/applications" || true
    fi
    if command -v gtk-update-icon-cache >/dev/null 2>&1 \
        && [ -f "$PREFIX/share/icons/hicolor/index.theme" ]; then
        gtk-update-icon-cache -q -t "$PREFIX/share/icons/hicolor" || true
    fi
}

uninstall() {
    rm -f -- "$BIN_PATH" "$DESKTOP_PATH" "$ICON_PATH"
    rm -rf -- "$LIB_DIR"
    refresh_caches
    printf 'Removed Minimal Game Launcher program files from %s\n' "$PREFIX"
    printf 'User data was kept: ~/.local/share/minigame-launcher, ~/.config/minigame-launcher, ~/.local/state/minigame-launcher\n'
    printf 'Delete those directories manually if you no longer need them.\n'
}

check_dependencies() {
    command -v python3 >/dev/null 2>&1 \
        || die "python3 not found. On Arch: sudo pacman -S python"
    python3 - <<'PY' >/dev/null 2>&1 || die "PyGObject with GTK 4 and libadwaita is missing. On Arch: sudo pacman -S python-gobject gtk4 libadwaita"
import gi
gi.require_version("Gtk", "4.0")
gi.require_version("Adw", "1")
from gi.repository import Adw, Gtk
PY
}

install_program() {
    check_dependencies

    [ -f "$ROOT/src/minimal_game_launcher/__main__.py" ] \
        || die "source package not found under $ROOT/src"

    mkdir -p -- "$LIB_DIR" "$PREFIX/bin"
    rm -rf -- "$LIB_DIR/minimal_game_launcher"
    cp -R -- "$ROOT/src/minimal_game_launcher" "$LIB_DIR/"
    find "$LIB_DIR/minimal_game_launcher" -name __pycache__ -type d -prune -exec rm -rf -- {} +

    lib_quoted=$(sh_quote "$LIB_DIR")
    {
        printf '#!/bin/sh\n'
        printf '# Generated by scripts/install.sh. Remove with scripts/install.sh --uninstall.\n'
        printf 'PYTHONPATH=%s exec python3 -m minimal_game_launcher "$@"\n' "$lib_quoted"
    } > "$BIN_PATH.tmp"
    chmod 755 -- "$BIN_PATH.tmp"
    mv -f -- "$BIN_PATH.tmp" "$BIN_PATH"

    mkdir -p -- "$(dirname -- "$DESKTOP_PATH")" "$(dirname -- "$ICON_PATH")"
    exec_value=$(desktop_exec_quote "$BIN_PATH")
    {
        while IFS= read -r line; do
            case $line in
                Exec=@EXEC@) printf 'Exec=%s\n' "$exec_value" ;;
                *) printf '%s\n' "$line" ;;
            esac
        done < "$ROOT/packaging/$APP_ID.desktop"
    } > "$DESKTOP_PATH.tmp"
    mv -f -- "$DESKTOP_PATH.tmp" "$DESKTOP_PATH"

    cp -- "$ROOT/packaging/$APP_ID.svg" "$ICON_PATH"

    if command -v desktop-file-validate >/dev/null 2>&1; then
        desktop-file-validate "$DESKTOP_PATH" || die "installed desktop entry is invalid"
    fi
    refresh_caches

    printf 'Installed Minimal Game Launcher to %s\n' "$PREFIX"
    printf 'Run: %s\n' "$BIN_PATH"
    case ":${PATH:-}:" in
        *":$PREFIX/bin:"*) ;;
        *) printf 'Note: %s/bin is not on PATH; use the full path or add it to PATH.\n' "$PREFIX" ;;
    esac
}

case "${1:-}" in
    "") install_program ;;
    --uninstall) uninstall ;;
    -h|--help)
        sed -n '2,12p' "$0"
        ;;
    *) die "unknown option: $1" ;;
esac
